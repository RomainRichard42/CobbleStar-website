CREATE TABLE IF NOT EXISTS player_collection_goals (
  user_id CHAR(36) NOT NULL,
  species VARCHAR(80) NOT NULL,
  favorite BOOLEAN NOT NULL DEFAULT FALSE,
  wanted BOOLEAN NOT NULL DEFAULT FALSE,
  target SMALLINT UNSIGNED NOT NULL DEFAULT 1,
  shiny BOOLEAN NOT NULL DEFAULT FALSE,
  note VARCHAR(160) NOT NULL DEFAULT '',
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (user_id,species),
  CONSTRAINT collection_user_fk FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
